# Admin module: load survey/config, run the optimiser and checker, publish
# the schedule.
#
# mod_admin_ui(id)
#   Takes: module id.
#   Returns: UI for the Admin page.
#
# mod_admin_server(id, con)
#   Takes: module id, con - DBI connection from db_connect().
#   Returns: reactive giving the current schedule data.frame
#            (person, machine, day, start, end), or NULL before one is run.
#
# Generate runs optimise_schedule() then check_schedule(). While either is
# still a stub (returns NULL) the stand-in data/fake_schedule.csv is loaded and
# the page says so. Publish sets a reactiveVal held inside the module.
# TODO: the returned reactive is not gated on "published" because the return
# value is fixed by the contract above.
# TODO: CLAUDE.md names the schedule column `day`; the brief asks for `date`.

mod_admin_ui <- function(id) {
  ns <- NS(id)
  tab <- function(title, out) nav_panel(title, uiOutput(ns(out)))
  layout_columns(
    col_widths = c(12, 12),
    card(
      card_header("Admin"),
      layout_columns(
        col_widths = c(3, 3, 3, 3),
        dateInput(ns("cycle_start"), "Cycle start date", format = "yyyy-mm-dd"),
        div(style = "margin-top: 32px;",
            actionButton(ns("generate"), "Generate schedule",
                         class = "btn-primary")),
        div(style = "margin-top: 32px;",
            actionButton(ns("publish"), "Publish")),
        div(style = "margin-top: 38px;", textOutput(ns("published_state")))
      ),
      uiOutput(ns("status")),
      DT::DTOutput(ns("schedule_table"))
    ),
    navset_card_tab(
      tab("Queue", "queue"),
      tab("Changes", "changes"),
      tab("No-shows", "noshows")
    )
  )
}

mod_admin_server <- function(id, con = NULL) {
  moduleServer(id, function(input, output, session) {
    schedule <- reactiveVal(NULL)
    published <- reactiveVal(FALSE)
    status <- reactiveVal(NULL)

    alert <- function(class, ...) div(class = paste("alert", class), ...)

    observeEvent(input$generate, {
      published(FALSE)
      survey <- tryCatch(load_survey(), error = function(e) NULL)
      config <- tryCatch(load_config(), error = function(e) NULL)
      sched <- tryCatch(optimise_schedule(survey, config), error = function(e) NULL)

      msgs <- list()
      if (is.data.frame(sched)) {
        msgs <- c(msgs, list(alert("alert-success",
                                   "Schedule generated by the optimiser.")))
      } else {
        sched <- readr::read_csv("data/fake_schedule.csv", col_types = readr::cols(.default = "c"), show_col_types = FALSE)
        msgs <- c(msgs, list(alert("alert-warning",
          "Optimiser not implemented yet: showing the stand-in data/fake_schedule.csv.")))
      }
      problems <- tryCatch(check_schedule(sched, survey, config),
                           error = function(e) NULL)
      msgs <- c(msgs, list(
        if (!is.data.frame(problems)) {
          alert("alert-warning", "Checker not implemented yet: schedule not checked.")
        } else if (nrow(problems) == 0) {
          alert("alert-success", "Checker: no problems found.")
        } else {
          alert("alert-danger", paste("Checker found", nrow(problems), "problem(s)."))
        }))
      schedule(sched)
      status(tagList(msgs))
    })

    observeEvent(input$publish, {
      if (is.null(schedule())) {
        showNotification("Generate a schedule first.", type = "error")
        return()
      }
      published(TRUE)
    })

    output$published_state <- renderText({
      if (published()) "Status: published" else "Status: not published"
    })
    output$status <- renderUI(status())
    output$schedule_table <- DT::renderDT({
      req(schedule())
      DT::datatable(schedule(), rownames = FALSE)
    })

    # TODO: Queue and Changes read the `queue` and `changes` tables once
    # Person 2 creates them; No-shows needs a definition from the bookings table.
    no_data <- p(class = "text-muted", "No data yet.")
    output$queue <- renderUI({
      if (!is.null(con) && DBI::dbExistsTable(con, "queue")) {
        tableOutput(session$ns("queue_tbl"))
      } else no_data
    })
    output$queue_tbl <- renderTable(DBI::dbReadTable(con, "queue"))
    output$changes <- renderUI({
      if (!is.null(con) && DBI::dbExistsTable(con, "changes")) {
        tableOutput(session$ns("changes_tbl"))
      } else no_data
    })
    output$changes_tbl <- renderTable(DBI::dbReadTable(con, "changes"))
    output$noshows <- renderUI(no_data)

    schedule
  })
}
